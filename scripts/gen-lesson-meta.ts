// Writes content/lessons/meta.ts (ids, titles, summaries) so screens that only list lessons
// don't bundle every lesson's full text. Runs automatically before `npm run build`.
import fs from 'node:fs';
import { LESSONS } from '../content/lessons';

const meta = LESSONS.map(({ id, unit, title, summary }) => ({ id, unit, title, summary }));
const out = `// GENERATED by scripts/gen-lesson-meta.ts — do not edit by hand.
export interface LessonMeta {
  id: string;
  unit: number;
  title: string;
  summary: string;
}

export const LESSON_META: LessonMeta[] = ${JSON.stringify(meta, null, 2)};
`;
fs.writeFileSync('content/lessons/meta.ts', out);
console.log(`lesson meta: ${meta.length} lessons`);
